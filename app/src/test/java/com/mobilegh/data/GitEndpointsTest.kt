/**
 * smart HTTP 的两个端点，以及服务发现响应的解析。
 *
 * 起因：我之前把服务发现写成了 `/git-info/refs`，那是 smart HTTP **响应**里
 * `# service=git-receive-pack` 的 service 名，不是请求路径；线上直接 404，
 * 用户看到的是「上传未完成。读取分支列表失败（HTTP 404）」。
 * 单测当时全绿，因为生产代码这一行从没被执行过（E2E 里那步是手工替做的）。
 *
 * 断言一律用**完整 URL**，不用 endsWith("git-receive-pack")：两个端点都以它结尾，
 * 后缀式断言对写反的 URL 同样为真，等于没测。
 */
class GitEndpointsTest {
    private val owner = "octocat"
    private val repo = "hello"

    @Test fun infoRefsIsTheServiceDiscoveryPath() {
        assertEquals(
            "https://github.com/octocat/hello.git/info/refs?service=git-receive-pack",
            GitPack.infoRefsUrl(owner, repo),
        )
    }

    @Test fun receivePackIsThePushPath() {
        assertEquals(
            "https://github.com/octocat/hello.git/git-receive-pack",
            GitPack.receivePackUrl(owner, repo),
        )
    }

    /** 两个端点必须是不同的 URL；写成同一个说明其中一个是错的 */
    @Test fun theTwoEndpointsDiffer() {
        assertFalse(GitPack.infoRefsUrl(owner, repo) == GitPack.receivePackUrl(owner, repo))
    }

    /** 我犯过的具体错误：把响应里的 service 名当路径。这里钉住它不会被改回去 */
    @Test fun discoveryPathIsNotGitInfoRefs() {
        val url = GitPack.infoRefsUrl(owner, repo)
        assertFalse("服务发现的路径不是 /git-info/refs", url.contains("/git-info/"))
        assertTrue(url.contains(".git/info/refs?"))
    }

