    private fun realDiscovery(): String {
        val bytes = realDiscoveryHex.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
        return String(bytes, Charsets.ISO_8859_1)
    }

    /** 用真字节跑生产解析器：上一版端点写错时 444 个单测全绿，因为这一行从没被执行过 */
    @Test fun parsesARealDiscoveryResponse() {
        val refs = GitPack.parseAdvertised(realDiscovery())

        // `.have` 不是 ref；它和 main 同 oid，混进来就会变成一条可借用的假分支
        assertEquals(39, refs.size)
        assertTrue(refs.none { it.name.contains(".have") })
        // 服务声明行与 capabilities 尾巴都不能当成 ref
        assertEquals(
            listOf("refs/heads/feat/code-download", "refs/heads/feat/fork-options"),
            refs.take(2).map { it.name },
        )
        assertEquals("afd883873395cf351b1d385270caf529880e824e", refs[0].oid)
        assertEquals("105c74097d50e66cce5ad434d5c6f2e15c2d4395", refs[1].oid)
        assertTrue(refs.all { it.name.startsWith("refs/") })
        // 真报文每行都以换行结尾。名字里带上它，写出来的指令就是坏的
        assertTrue(refs.all { !it.name.contains('\u0000') && !it.name.contains("\n") && it.name == it.name.trim() })
    }

    /** 借 ref：必须借到服务端确实存在、且 oid 完整的一条 */
    @Test fun pickRefFromRealResponseUsesTheServerOid() {
        val refs = GitPack.parseAdvertised(realDiscovery())
        // baseRef 是分支名（可含斜杠），不是最后一段
        val got = GitPack.pickRef(refs, "feat/fork-options")
        assertEquals("refs/heads/feat/fork-options", got?.name)
        assertEquals("105c74097d50e66cce5ad434d5c6f2e15c2d4395", got?.oid)
        assertEquals("refs/heads/main", GitPack.pickRef(refs, "main")?.name)
        // 不存在的 baseRef 退到任意分支，而不是编一条出来
        assertEquals("refs/heads/feat/code-download", GitPack.pickRef(refs, "nope")?.name)
        assertNull(GitPack.pickRef(emptyList(), "main"))
    }

    /**
     * 借来的 ref 直接拼进更新指令。名字带着 pkt-line 的行尾换行时，
     * 指令会变成两行，服务端只会回一句看不懂的 `unpack no voting servers succeeded`。
     */
    @Test fun noOpCommandFromARealRefIsOneLine() {
        val ref = GitPack.pickRef(GitPack.parseAdvertised(realDiscovery()), "main")!!
        val command = GitPack.noOpCommand(ref)
        assertEquals("refs/heads/main", command.substringBefore('\u0000').substringAfterLast(' '))
        assertEquals(1, command.count { it == '\n' })
        assertTrue(command.endsWith("\u0000report-status\n"))
    }

    /** 空仓库：服务发现只有服务声明和 flush，一条 ref 都没有 */
    @Test fun emptyRepositoryAdvertisesNoRefs() {
        val bytes = ByteArrayOutputStream().apply {
            write(GitPack.pktLine("# service=git-receive-pack"))
            write(GitPack.FLUSH)
            write(GitPack.FLUSH)
        }.toByteArray()
        assertEquals(emptyList<GitPack.Ref>(), GitPack.parseAdvertised(String(bytes, Charsets.ISO_8859_1)))
    }
